# ### Демонстрация продукта
# Анализ WAV-файлов с известными параметрами (`tools/make_test_wavs.py`: fs 48 кГц, несущая ≈ 9 кГц,
# ОСШ 15 дБ в полосе сигнала).

# %%
from amc.infer import Classifier, analyze  # noqa: E402

wav_dir = ROOT / "data" / "test_wavs"
if (wav_dir / "truth.csv").exists():
    truth = pd.read_csv(wav_dir / "truth.csv").set_index("cls")
    clf = Classifier()
    demo = []
    for cls in truth.index:
        r = analyze(wav_dir / f"{cls}_iq.wav", clf)
        t = truth.loc[cls]
        demo.append({"истина": cls, "распознано": r["modulation"], "уверенность": round(r["confidence"], 2),
                     "несущая (истина / оценка), Гц": f"{t.carrier_Hz:.0f} / {r['carrier_Hz']:.0f}",
                     "скорость (истина / оценка), Бод": (f"{t.symbol_rate_Bd:.0f} / {r['symbol_rate_Bd']:.0f}"
                                                         if r["symbol_rate_Bd"] and t.symbol_rate_Bd == t.symbol_rate_Bd
                                                         else "—"),
                     "полоса (истина / оценка), Гц": f"{t.bw99_Hz:.0f} / {r['bandwidth99_Hz']:.0f}"})
    display(pd.DataFrame(demo).set_index("истина"))
else:
    print("тестовые WAV не созданы: python tools/make_test_wavs.py data/test_wavs")

