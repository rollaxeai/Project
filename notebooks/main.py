# ## Этап 3. Нейросети (`03_deep_models`)
# VT-CNN2 (из литературы), ResNet-1D, CNN-LSTM; вход — I/Q, нормированные по мощности; аугментации на GPU
# (поворот фазы, сдвиг частоты, инверсия спектра); AdamW + OneCycle, bf16, ранняя остановка; 3 seed'а; MLflow.

# %%
rows = []
for name, run_rml, run_syn in [("VT-CNN2", "rml2016a_vtcnn2_iq_aug_s{}", None),
                               ("ResNet-1D", "rml2016a_resnet_iq_aug_s{}", "synth_v1_resnet_iq_aug_s{}"),
                               ("CNN-LSTM", "rml2016a_cnnlstm_iq_aug_s{}", "synth_v1_cnnlstm_iq_aug_s{}_e60")]:
    r = {"модель": name}
    for col, tpl in [("RadioML", run_rml), ("свой (1024)", run_syn)]:
        if tpl is None:
            continue
        m = [metrics(tpl.format(s)) for s in range(3)]
        acc = np.array([x["test_acc"] for x in m])
        r[f"{col}: acc"] = f"{acc.mean():.1%} ± {acc.std(ddof=1):.1%}"
        r[f"{col}: ОСШ≥0"] = f"{np.mean([x['test_acc_snr>=0'] for x in m]):.1%}"
    rows.append(r)
rows.insert(0, {"модель": "LightGBM (признаки)", "RadioML: acc": "54.8%", "RadioML: ОСШ≥0": "83.7%",
                "свой (1024): acc": "51.4%", "свой (1024): ОСШ≥0": "75.3%"})
pd.DataFrame(rows).set_index("модель").fillna("—")

